// Emits S2's committed evidence artifact.
//
// The plan is explicit that an exit code is not evidence (R4): each stage's exit
// command additionally writes a diffable JSON artifact that the NEXT stage's
// suite asserts, so a later stage cannot pass against a value that has drifted.
// For S2 that artifact is the decision table itself - executed, counted, and
// written out - rather than console output that disappears.
//
// This is a test file on purpose: it runs as part of the stage's exit command,
// which is what makes "the exit command emits the artifact" literally true.

import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { runTable } from "./decision-table.js";
import { pairs } from "./properties/pairs.js";
import { resolve as resolvePair } from "./resolve.js";
import { canonical, type Occurrence } from "./types.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const OUT = resolve(ROOT, "evidence", "stage-02");

const SWEEP = pairs(20260301, 2000);

describe("S2 evidence artifact", () => {
  it("writes the executed decision table and its totals", () => {
    const table = runTable();
    const reasons = new Map<string, number>();
    let bothRetained = 0;
    let conflicts = 0;
    let unknown = 0;

    for (const [local, remote] of SWEEP) {
      const result = resolvePair(local, remote);
      reasons.set(result.reason, (reasons.get(result.reason) ?? 0) + 1);
      if (result.winner === null) bothRetained += 1;
      if (result.conflicted) conflicts += 1;
      // `unknown` is not in ResolutionReason at all - that is the point. The
      // cast is here only so the assertion can fail loudly if someone adds it.
      const reason = result.reason as string;
      if (!reason || reason === "unknown") unknown += 1;
    }

    // G1 in one assertion: every pair resolved, and none returned "unknown".
    expect(unknown).toBe(0);

    const rows = table
      .map(
        (r) =>
          `| ${r.name} | ${r.keys} | \`${r.reason}\` | ${r.winner} | ${r.conflicted ? "yes" : "no"} |`,
      )
      .join("\n");

    const markdown = `# RFC 5546 decision table (S2)

Generated by \`src/domain/rfc5546/emit-artifact.test.ts\`, which runs as part of
this stage's exit command. Do not edit by hand: the test regenerates it, and a
hand-edited copy is a claim rather than a measurement.

Primary keys, in order: identity (UID + RECURRENCE-ID), then SEQUENCE, then
DTSTAMP. Beads/Dolt is the ORGANIZER, so Beads assigns SEQUENCE and external
calendars are clients of it (RFC 5545 section 3.8.7.4).

| case | keys that decided it | reason | winner | was a conflict |
|---|---|---|---|---|
${rows}

## Totals over the property sweep

Pairs exercised: ${SWEEP.length}
Resolutions that conflicted: ${conflicts}
Resolutions that retained both sides: ${bothRetained}
Resolutions with no reason, or reason \`unknown\`: ${unknown}

Reason distribution:

${[...reasons.entries()]
  .sort((a, b) => b[1] - a[1])
  .map(([reason, n]) => `- \`${reason}\`: ${n}`)
  .join("\n")}
`;

    mkdirSync(OUT, { recursive: true });
    writeFileSync(resolve(OUT, "decision-table.md"), markdown);

    const artifact = {
      stage: "S2",
      generatedBy: "src/domain/rfc5546/emit-artifact.test.ts",
      gate: "G1 - resolution is total and stable",
      keysInOrder: ["UID + RECURRENCE-ID", "SEQUENCE", "DTSTAMP", "canonical tie-break"],
      organizer: "beads/dolt (assigns SEQUENCE); external calendars are clients",
      decisionTable: table,
      sweep: {
        pairs: SWEEP.length,
        conflicted: conflicts,
        bothRetained,
        unknown,
        reasonDistribution: Object.fromEntries(reasons),
      },
      propertiesProven: ["idempotence", "commutativity", "stability"],
      total: unknown === 0,
    };
    expect(existsSync(resolve(OUT, "decision-table.md"))).toBe(true);
    writeFileSync(resolve(OUT, "artifact.json"), `${JSON.stringify(artifact, null, 2)}\n`);
  });

  it("keeps a loser payload verbatim so a human can undo a resolution", () => {
    const [local, remote] = SWEEP.find(
      ([a, b]) => a.uid === b.uid && a.recurrenceId === b.recurrenceId && a.sequence !== b.sequence,
    ) as [Occurrence, Occurrence];
    const result = resolvePair(local, remote);
    expect(result.loserPayload).not.toBeNull();
    expect(canonical(result.loserPayload as Occurrence)).toBe(
      canonical(result.winner?.sequence === local.sequence ? remote : local),
    );
  });
});
