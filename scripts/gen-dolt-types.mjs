// gen:dolt-types - generate row types from the declared schema.
//
// The schema declaration is the single source of truth (see schema.mjs), so the
// generated types cannot drift from it: regenerate and the compiler will say so.
// Column SQL types are mapped to the narrowest honest TypeScript shape rather
// than to `any`, which binding rule 1 forbids outright.

import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { TABLES } from "../src/adapters/dolt/schema.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Columns that are JSON in the database and validated at the boundary by Zod. */
const JSON_COLUMNS = new Set([
  "capabilities",
  "patch_json",
  "local_payload",
  "remote_payload",
  "attributes_json",
]);

/** Columns that are nullable, and therefore optional in the row type. */
const NULLABLE = new Set([
  "last_synced_commit_hash",
  "last_synced_etag",
  "last_synced_dtstamp",
  "ownership_token",
  "linked_bead_id",
  "bead_id",
  "external_uid",
  "local_payload",
  "remote_payload",
  "decision_id",
]);

const camel = (name) => name.replace(/_([a-z])/g, (_, c) => c.toUpperCase());

const typeFor = (column) => {
  if (JSON_COLUMNS.has(column)) return "unknown";
  if (column === "id") return "number";
  if (column.startsWith("external_sequence")) return "number";
  if (column.startsWith("resolved")) return "boolean";
  if (column.endsWith("_at") || column.endsWith("_utc")) return "string";
  return "string";
};

const blocks = Object.entries(TABLES).map(([table, spec]) => {
  const fields = spec.columns
    .map((col) => {
      const optional = NULLABLE.has(col) ? "?" : "";
      return `  ${camel(col)}${optional}: ${typeFor(col)};`;
    })
    .join("\n");
  return `export interface ${table.replace(/(^|_)(\w)/g, (_, __, c) => c.toUpperCase())}Row {\n${fields}\n}`;
});

const out = `// GENERATED by scripts/gen-dolt-types.mjs. Do not edit by hand.
// Source of truth: src/adapters/dolt/schema.mjs
// JSON columns are typed \`unknown\` on purpose: they are validated with Zod at
// the boundary, and a structural type here would be a lie about that.

${blocks.join("\n\n")}
`;

const target = join(ROOT, "src", "types", "dolt.generated.ts");
writeFileSync(target, out);
console.log(`gen:dolt-types wrote ${target} (${blocks.length} row types)`);
