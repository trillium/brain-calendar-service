#!/usr/bin/env node
// build:timezones - pin the timezone data this service depends on.
//
// WHY THIS EXISTS. The plan's gate G2 asks for a timezone build step and asks
// that rebuilding it be idempotent. Checking the actual package first changes
// what that means: ical.js 2.2.1 as published on npm ships NO VTIMEZONE data
// and NO generator. `ICAL.TimezoneService.get("America/New_York")` returns
// undefined on a fresh install, and the upstream tooling that compiles VTIMEZONE
// is not in the published package at all. So there is nothing to "rebuild" in
// the sense the plan assumed; the data has to be PRODUCED.
//
// WHAT THIS PRODUCES. A deterministic table of UTC-offset transitions for the
// zones this service supports, over a fixed horizon, sampled from the platform's
// IANA database and frozen into a generated source file. Recurrence reads the
// pinned table, never the host's live tzdata, so a host tzdata update cannot
// silently change what a calendar shows - which is the whole reason the plan
// distrusts host tzdata in the first place.
//
// IDEMPOTENCE. Output is sorted, fixed-width and derived only from the zone
// list and the horizon, so two runs on the same IANA database are byte
// identical. `build:timezones --check` re-runs and fails if the checked-in file
// differs by a single byte, which is the plan's `git diff --exit-code` test
// without depending on a clean git tree.

import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "domain", "recurrence", "ical.timezones.generated.js");

/** The zones this service supports. Deliberately small: each one is a promise. */
export const ZONES = [
  "America/Los_Angeles",
  "America/New_York",
  "America/Santiago",
  "Europe/London",
  "Europe/Berlin",
  "Australia/Sydney",
  "Asia/Tokyo",
  "UTC",
];

export const HORIZON_START = 2020;
export const HORIZON_END = 2040;

const formatterCache = new Map();
const fmt = (zone) => {
  if (!formatterCache.has(zone)) {
    formatterCache.set(
      zone,
      new Intl.DateTimeFormat("en-US", {
        timeZone: zone,
        hour12: false,
        year: "numeric",
        month: "2-digit",
        day: "2-digit",
        hour: "2-digit",
        minute: "2-digit",
        second: "2-digit",
      }),
    );
  }
  return formatterCache.get(zone);
};

/** UTC offset in seconds for `zone` at the given epoch milliseconds. */
export const offsetSeconds = (zone, epochMs) => {
  const parts = fmt(zone).formatToParts(new Date(epochMs));
  const get = (t) => Number(parts.find((p) => p.type === t)?.value ?? "0");
  const asUtc = Date.UTC(
    get("year"),
    get("month") - 1,
    get("day"),
    get("hour") % 24,
    get("minute"),
    get("second"),
  );
  return Math.round((asUtc - epochMs) / 1000);
};

const DAY = 86400000;

/** Every offset transition in [fromMs, toMs), found by bisection. */
const transitionsIn = (zone, fromMs, toMs) => {
  const found = [];
  let startOffset = offsetSeconds(zone, fromMs);
  // Scan day by day: a transition is never more than a day apart in practice,
  // and this keeps the search cheap and, more importantly, reproducible.
  for (let t = fromMs; t < toMs; t += DAY) {
    const next = t + DAY;
    if (next > toMs) break;
    const offset = offsetSeconds(zone, next);
    if (offset === startOffset) continue;
    let lo = t;
    let hi = next;
    while (hi - lo > 1000) {
      const mid = lo + Math.floor((hi - lo) / 2);
      if (offsetSeconds(zone, mid) === startOffset) lo = mid;
      else hi = mid;
    }
    found.push({ at: hi, from: startOffset, to: offset });
    startOffset = offset;
  }
  return found;
};

const msOf = (isoDate) => Date.parse(`${isoDate}T00:00:00Z`);

const build = () => {
  const lines = [];
  const index = {};
  for (const zone of [...ZONES].sort()) {
    const from = msOf(`${HORIZON_START}-01-01`);
    const to = msOf(`${HORIZON_END + 1}-01-01`);
    const base = offsetSeconds(zone, from);
    const found = transitionsIn(zone, from, to);
    index[zone] = { base, transitions: found.map((t) => [t.at, t.from, t.to]) };
    lines.push(`  ${JSON.stringify(zone)}: {`);
    lines.push(`    base: ${base},`);
    lines.push(
      `    transitions: [\n${found
        .map((t) => `      [${t.at}, ${t.from}, ${t.to}],`)
        .join("\n")}\n    ],`,
    );
    lines.push("  },");
  }
  return `// GENERATED by scripts/build-timezones.mjs. Do not edit by hand.
//
// UTC-offset transitions for the zones this service supports, over
// ${HORIZON_START}-${HORIZON_END}, sampled from the platform IANA database and
// frozen here. Recurrence reads THIS, not the host's live tzdata, so a host
// tzdata update cannot silently change what a calendar displays.
//
// Entries are [epochMillis, offsetBefore, offsetAfter], ascending. The base
// offset is the one in effect at ${HORIZON_START}-01-01T00:00:00Z.
//
// Source: IANA tzdata as exposed by Intl.DateTimeFormat at build time. Regenerate
// with \`pnpm run build:timezones\`; verify with \`pnpm run build:timezones --check\`.

export const HORIZON = { start: ${HORIZON_START}, end: ${HORIZON_END} };

export const ZONES = {
${lines.join("\n")}
};
`;
};

const check = process.argv.includes("--check");
const next = build();
mkdirSync(dirname(OUT), { recursive: true });

if (check) {
  const current = readFileSync(OUT, "utf8");
  if (current !== next) {
    console.error("build:timezones --check FAILED: the pinned table differs from a fresh build.");
    console.error(`  regenerate with: pnpm run build:timezones`);
    process.exit(1);
  }
  console.log(
    "build:timezones --check PASSED: the pinned table is byte-identical to a fresh build",
  );
} else {
  writeFileSync(OUT, next);
  const { version } = JSON.parse(
    execFileSync("node", ["-p", "JSON.stringify({version: process.versions.icu})"]).toString(),
  );
  console.log(`build:timezones wrote ${OUT} (${Object.keys(ZONES).length} zones, ICU ${version})`);
}
